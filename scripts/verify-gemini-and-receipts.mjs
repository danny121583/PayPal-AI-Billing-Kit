function assertMerchantBrandedPdf(pdfBuffer, label, options = {}) {
  const text = pdfBuffer.toString('latin1');
  if (!text.startsWith('%PDF-1.4')) {
    throw new Error(`[${label}] Missing %PDF-1.4 header`);
  }
  if (!text.includes('%%EOF')) {
    throw new Error(`[${label}] Missing %%EOF trailer`);
  }
  // Must NOT contain old technical footer or internal terminology
  const forbidden = [
    'Generated by PayPal AI Billing Kit Unified MCP Gateway',
    'Zero PHI Administrative Ledger',
    'PROVENANCE:',
    'SERVICE CODE',
    'ADMINISTRATIVE DESCRIPTION',
  ];
  for (const term of forbidden) {
    if (text.includes(term)) {
      throw new Error(`[${label}] PDF still contains forbidden internal term: "${term}"`);
    }
  }
  // Must contain electronic receipt footer
  const expectedFooter =
    options.expectedFooter ||
    'This receipt was generated electronically. Please retain it for your records.';
  if (!text.includes(expectedFooter)) {
    throw new Error(`[${label}] PDF missing required footer: "${expectedFooter}"`);
  }
  if (options.expectedMerchant && !text.includes(options.expectedMerchant)) {
    throw new Error(`[${label}] PDF missing expected merchant name: "${options.expectedMerchant}"`);
  }
  if (options.expectedPresentationState && !text.includes(options.expectedPresentationState)) {
    throw new Error(
      `[${label}] PDF missing expected presentation state: "${options.expectedPresentationState}"`
    );
  }
  if (options.expectPayPalAttribution && !text.includes('Payment processed through PayPal')) {
    throw new Error(`[${label}] PDF missing "Payment processed through PayPal" attribution`);
  }
  if (options.expectSandboxLabel && !text.includes('PayPal Sandbox Test Transaction')) {
    throw new Error(`[${label}] PDF missing "PayPal Sandbox Test Transaction" label`);
  }
}

